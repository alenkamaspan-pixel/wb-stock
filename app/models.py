"""
Константы предметной области.

Ключевая идея: текущий остаток товара на складе НИГДЕ не хранится отдельным
числом. Он всегда вычисляется как сумма всех движений (таблица
stock_movements) по данному товару и складу. Это защищает от рассинхрона:
если что-то пошло не так, остаток всегда можно пересчитать заново по истории
движений, и всегда видно, ОТКУДА взялась текущая цифра.
"""

USER_ROLES = ("admin", "manager", "viewer")


class MovementType:
    INCOME = "income"                  # приход от поставщика
    SALE = "sale"                      # продажа по заказу FBS (списание)
    SALE_REVERSAL = "sale_reversal"    # отмена/возврат заказа (возврат остатка)
    TRANSFER_OUT = "transfer_out"      # перемещение — списание с исходного склада
    TRANSFER_IN = "transfer_in"        # перемещение — приход на целевой склад
    WRITEOFF = "writeoff"              # списание (брак, недостача и т.п.)
    ADJUSTMENT = "adjustment"          # ручная корректировка (инвентаризация)


class MovementSource:
    MANUAL = "manual"          # внесено человеком через интерфейс
    WB_SYNC = "wb_sync"        # создано автоматически синхронизацией с WB
    OZON_SYNC = "ozon_sync"    # создано автоматически синхронизацией с Ozon (FBS-продажи, загрузка FBO-поставки)


# 30.09.2026: «Внешние списания» — один общий раздел с тремя вкладками (см.
# обсуждение с Алёной). WB FBS остаётся полностью автоматическим (см.
# sync.py) — сюда не относится. Все три вида ниже — чисто ручные: списание
# с ФФ, зафиксированное в этом журнале, физически уезжает на маркетплейс и
# больше не учитывается как отдельный склад с текущим балансом.
class ExternalWriteoffKind:
    FBO_WB = "fbo_wb"
    FBO_OZON = "fbo_ozon"
    FBS_OZON = "fbs_ozon"

    ALL = (FBO_WB, FBO_OZON, FBS_OZON)

    LABELS = {
        FBO_WB: "FBO WB",
        FBO_OZON: "FBO Ozon",
        FBS_OZON: "FBS Ozon",
    }
